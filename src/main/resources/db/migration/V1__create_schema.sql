-- Base plans: every subscriber is on exactly one. Plan data is refilled when the plan changes.
CREATE TABLE plan (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR2(20)  NOT NULL UNIQUE,
    name                VARCHAR2(60)  NOT NULL,
    monthly_fee         NUMBER(10, 2) NOT NULL CHECK (monthly_fee >= 0),
    data_gb             NUMBER(5)     NOT NULL,
    voice_minutes       NUMBER(6)     NOT NULL,
    max_bandwidth_kbps  NUMBER(8)     NOT NULL
);

CREATE TABLE subscriber (
    id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn             VARCHAR2(11)  NOT NULL UNIQUE,
    full_name          VARCHAR2(100) NOT NULL,
    nic                VARCHAR2(12)  NOT NULL,
    balance            NUMBER(10, 2) DEFAULT 0 NOT NULL CHECK (balance >= 0),
    status             VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    plan_id            NUMBER        NOT NULL REFERENCES plan (id),
    plan_data_used_mb  NUMBER(12)    DEFAULT 0 NOT NULL CHECK (plan_data_used_mb >= 0),
    -- held for open charging sessions: granted to the gateway but not yet reported as used
    plan_data_reserved_mb  NUMBER(12)    DEFAULT 0 NOT NULL CHECK (plan_data_reserved_mb >= 0),
    balance_reserved       NUMBER(10, 2) DEFAULT 0 NOT NULL CHECK (balance_reserved >= 0),
    created_at         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT chk_balance_reserved CHECK (balance_reserved <= balance)
);

CREATE INDEX idx_subscriber_plan ON subscriber (plan_id);

-- audit trail written by the CHANGE_PLAN procedure
CREATE TABLE plan_change (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id  NUMBER        NOT NULL REFERENCES subscriber (id),
    old_plan_id    NUMBER        NOT NULL REFERENCES plan (id),
    new_plan_id    NUMBER        NOT NULL REFERENCES plan (id),
    fee_charged    NUMBER(10, 2) NOT NULL,
    changed_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX idx_plan_change_subscriber ON plan_change (subscriber_id);

-- Packages a subscriber can buy on top of their plan.
--   app NULL -> add-on data any app can use (Extra 25GB)
--   app 'X'  -> only traffic the network tags as app X (YouTube Unlimited)
--   data_mb NULL -> unlimited; after fair_usage_mb the speed drops to throttled_bandwidth_kbps
CREATE TABLE data_package (
    id                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                      VARCHAR2(20)  NOT NULL UNIQUE,
    name                      VARCHAR2(60)  NOT NULL,
    app                       VARCHAR2(20)  CHECK (app IN ('YOUTUBE', 'WHATSAPP', 'FACEBOOK')),
    price                     NUMBER(10, 2) NOT NULL CHECK (price >= 0),
    data_mb                   NUMBER(12)    CHECK (data_mb > 0),
    validity_days             NUMBER(4)     NOT NULL CHECK (validity_days > 0),
    max_bandwidth_kbps        NUMBER(8)     NOT NULL,
    fair_usage_mb             NUMBER(12),
    throttled_bandwidth_kbps  NUMBER(8),
    CONSTRAINT chk_fair_usage CHECK (
        (fair_usage_mb IS NULL AND throttled_bandwidth_kbps IS NULL)
        OR (fair_usage_mb IS NOT NULL AND throttled_bandwidth_kbps IS NOT NULL))
);

-- one row per package a subscriber bought; usage counts up in data_mb_used
CREATE TABLE subscriber_package (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id  NUMBER     NOT NULL REFERENCES subscriber (id),
    package_id     NUMBER     NOT NULL REFERENCES data_package (id),
    data_mb_used   NUMBER(12) DEFAULT 0 NOT NULL CHECK (data_mb_used >= 0),
    data_mb_reserved NUMBER(12) DEFAULT 0 NOT NULL CHECK (data_mb_reserved >= 0),
    activated_at   TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at     TIMESTAMP  NOT NULL
);

CREATE INDEX idx_subscriber_package_sub ON subscriber_package (subscriber_id, expires_at);

-- Charging records written by RECORD_USAGE. One usage event can be split across several buckets,
-- so each bucket's share is its own row and usage_ref groups the rows of one event.
CREATE TABLE usage_record (
    id                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_ref              VARCHAR2(36)  NOT NULL,
    subscriber_id          NUMBER        NOT NULL REFERENCES subscriber (id),
    app                    VARCHAR2(20)  NOT NULL,
    source                 VARCHAR2(10)  NOT NULL CHECK (source IN ('PACKAGE', 'PLAN', 'BALANCE')),
    subscriber_package_id  NUMBER        REFERENCES subscriber_package (id),
    data_mb                NUMBER(12)    NOT NULL,
    money_charged          NUMBER(10, 2) DEFAULT 0 NOT NULL,
    recorded_at            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX idx_usage_record_ref ON usage_record (usage_ref);
CREATE INDEX idx_usage_record_sub ON usage_record (subscriber_id, recorded_at);
