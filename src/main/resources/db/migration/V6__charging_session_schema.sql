-- Online charging sessions (gateway -> backend). The gateway starts a session when a subscriber
-- begins using an app, asks for quota in chunks, reports what was used, and releases at the end.
CREATE TABLE charging_session (
    id             VARCHAR2(36)  PRIMARY KEY,                -- UUID created by the backend
    subscriber_id  NUMBER        NOT NULL REFERENCES subscriber (id),
    app            VARCHAR2(20)  NOT NULL,
    status         VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL CHECK (status IN ('OPEN', 'RELEASED')),
    total_used_mb  NUMBER(12)    DEFAULT 0 NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    released_at    TIMESTAMP
);

CREATE INDEX idx_charging_session_sub ON charging_session (subscriber_id, status);

-- Every processed request of a session, by the gateway's request number (start = 0, then 1, 2, ...).
-- The primary key makes a repeated request fail instead of charging twice, even if the
-- Redis idempotency store has lost its key (ID-8).
CREATE TABLE charging_request (
    session_id      VARCHAR2(36) NOT NULL REFERENCES charging_session (id),
    request_number  NUMBER(10)   NOT NULL CHECK (request_number >= 0),
    request_type    VARCHAR2(10) NOT NULL CHECK (request_type IN ('START', 'UPDATE', 'RELEASE')),
    processed_at    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_charging_request PRIMARY KEY (session_id, request_number)
);

-- One grant given to the gateway. While ACTIVE its MB (or money) is held in the bucket's
-- reserved column so no other session can spend it; on commit only the used part is charged.
CREATE TABLE quota_reservation (
    id                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             VARCHAR2(36)  NOT NULL REFERENCES charging_session (id),
    source                 VARCHAR2(10)  NOT NULL CHECK (source IN ('PACKAGE', 'PLAN', 'BALANCE')),
    subscriber_package_id  NUMBER        REFERENCES subscriber_package (id),
    reserved_mb            NUMBER(12)    NOT NULL CHECK (reserved_mb > 0),
    money_reserved         NUMBER(10, 2) DEFAULT 0 NOT NULL,
    used_mb                NUMBER(12),
    status                 VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'COMMITTED')),
    created_at             TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    committed_at           TIMESTAMP
);

-- at most one active grant per session
CREATE UNIQUE INDEX uq_reservation_active ON quota_reservation (
    CASE WHEN status = 'ACTIVE' THEN session_id END
);
