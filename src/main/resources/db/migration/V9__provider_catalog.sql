-- Group 6 (PR-2): provider staff manage the catalog and suspend subscribers, so every such change
-- records who made it (the staff member's login name from the SSO token) and when.
-- The full audit table of grants, denies, blocks and unblocks comes with group 7 (OB-1).

-- A package is never deleted (old purchases point to it): it stops being sold instead.
ALTER TABLE data_package ADD (
    active      VARCHAR2(1) DEFAULT 'Y' NOT NULL CONSTRAINT chk_data_package_active CHECK (active IN ('Y', 'N')),
    updated_by  VARCHAR2(64),
    updated_at  TIMESTAMP WITH TIME ZONE
);

ALTER TABLE plan ADD (
    updated_by  VARCHAR2(64),
    updated_at  TIMESTAMP WITH TIME ZONE
);

-- who suspended / unsuspended the subscriber last
ALTER TABLE subscriber ADD (
    status_changed_by  VARCHAR2(64),
    status_changed_at  TIMESTAMP WITH TIME ZONE
);

-- Every price a package ever had. Filled by the trigger below, so no code path can change a price
-- without leaving a row here.
CREATE TABLE data_package_price (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id  NUMBER        NOT NULL REFERENCES data_package (id),
    old_price   NUMBER(10, 2),                                -- NULL: the package was created
    new_price   NUMBER(10, 2) NOT NULL CHECK (new_price >= 0),
    changed_by  VARCHAR2(64)  NOT NULL,
    changed_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_data_package_price_pkg ON data_package_price (package_id, changed_at);

CREATE OR REPLACE TRIGGER trg_data_package_price
    AFTER INSERT OR UPDATE OF price ON data_package
    FOR EACH ROW
    WHEN (OLD.price IS NULL OR NEW.price <> OLD.price)
BEGIN
    INSERT INTO data_package_price (package_id, old_price, new_price, changed_by)
    VALUES (:NEW.id, :OLD.price, :NEW.price, NVL(:NEW.updated_by, 'system'));
END;
